namespace myclean::indexer {

// A build-output or cache folder that the indexer crawls.
struct IndexedFolder {
  std::filesystem::path path;
  std::string category;  // the attribution category: build-artifacts, dev-caches or app-caches
  std::string label;     // the area's label, or "Output of projects with <marker>"

  friend bool operator==(const IndexedFolder&, const IndexedFolder&) = default;
};

// Whether folders of attribution `category` are kept out of the index: build-artifacts,
// dev-caches and app-caches, which change all the time and are regenerated by their tools.
[[nodiscard]] bool kept_out(map::Category category);

// What the knowledge packs say a build-output or cache folder is.
struct Knowledge {
  std::span<const map::Area> areas;               // every attribution area; kept_out() ones count
  std::span<const rules::CleaningRule> rules;     // every clean case; the project ones count
  const clean::Workspaces* workspaces = nullptr;  // null: no project is looked for
};

// The build-output and cache folders the indexer crawls (scope.included), sorted by path:
//  - every existing folder an area of a kept_out() category names (%VARIABLES% expanded with
//    `environment`, '*' and '?' matched within one component, "?:\" on every fixed volume);
//  - in every project below the workspace roots (a folder holding the marker of a clean case
//    with a project marker, at most max_depth levels down, never entering a folder named in
//    workspaces.skip, a link or a cloud placeholder), the folders the case's targets select
//    there (holding require.contains, when the case sets it).
// A folder inside another one found is left out: excluding the outer one covers it. Fails as
// scope.included() does (the indexer is not running), or when `stop` is requested.
[[nodiscard]] Result<std::vector<IndexedFolder>> indexed_build_folders(
    const IIndexerScope& scope, const clean::IFileTree& tree,
    const clean::IEnvironment& environment, const Knowledge& knowledge,
    const std::stop_token& stop);

}  // namespace myclean::indexer
